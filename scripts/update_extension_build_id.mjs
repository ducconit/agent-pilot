#!/usr/bin/env node
/**
 * Generate a stable source/artifact fingerprint for the unpacked extension.
 * The file itself is excluded from the input set so running this repeatedly is
 * idempotent. The bridge reports this beside the human-facing version because
 * development reloads often keep the same manifest version.
 */
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const extensionRoot = path.join(root, "extensions");
const generated = path.join(extensionRoot, "background", "build-info.js");
const hash = crypto.createHash("sha256");

async function collect(directory) {
  const entries = (await fs.readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    const relative = path.relative(extensionRoot, absolute).split(path.sep).join("/");
    if (relative === "background/build-info.js") continue;
    if (entry.isDirectory()) {
      await collect(absolute);
      continue;
    }
    if (!entry.isFile()) continue;
    hash.update(relative);
    hash.update("\0");
    hash.update(await fs.readFile(absolute));
    hash.update("\0");
  }
}

await collect(extensionRoot);
const buildId = `sha256:${hash.digest("hex").slice(0, 16)}`;
const content = `// Generated by scripts/update_extension_build_id.mjs.\nexport const EXTENSION_BUILD_ID = ${JSON.stringify(buildId)};\n`;
if ((await fs.readFile(generated, "utf8").catch(() => "")) !== content) {
  await fs.writeFile(generated, content, "utf8");
}
console.log(buildId);
